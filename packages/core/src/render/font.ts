export const GLYPHS: Record<string, string[]> = {};
for (const key of Object.keys(GLYPH_SRC)) {
  GLYPHS[key] = GLYPH_SRC[key]!.split("/");
}

export function normalizeText(text: string | number): string {
  return String(text).toUpperCase().replace(/×/g, "X").replace(/−/g, "-");
}

export function measurePixelText(text: string | number, size: number): number {
  const value = normalizeText(text);
  if (!value.length) return 0;
  return (value.length * 6 - 1) * size;
}

/**
 * 在逻辑像素坐标里画一行像素字（不做 DPR 处理，调用方负责 transform）。
 * shadowColor 会往右下偏移一个像素单位，得到硬阴影。
 */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string | number,
  x: number,
  y: number,
  size: number,
  color: string,
  shadowColor?: string | null,
): number {
  const value = normalizeText(text);
  const s = Math.max(1, Math.round(size));
  const px = Math.round(x);
  const py = Math.round(y);

  const paint = (offsetX: number, offsetY: number, ink: string): void => {
    ctx.fillStyle = ink;
    let cursor = px + offsetX;
    for (let i = 0; i < value.length; i += 1) {
      const glyph = GLYPHS[value[i]] ?? GLYPHS["?"]!;
      for (let row = 0; row < 7; row += 1) {
        const line = glyph[row] ?? "";
        for (let col = 0; col < 5; col += 1) {
          if (line[col] === "1") {
            ctx.fillRect(cursor + col * s, py + offsetY + row * s, s, s);
          }
        }
      }
      cursor += 6 * s;
    }
  };

  if (shadowColor) paint(s, s, shadowColor);
  paint(0, 0, color);
  return measurePixelText(value, s);
}
